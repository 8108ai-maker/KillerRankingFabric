"""Emits KillerRankingSounds.java from sounds.json so constants never drift from assets."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOUNDS_JSON = ROOT / "src/client/resources/assets/killerranking/sounds.json"
JAVA = ROOT / "src/main/java/dev/killerranking/KillerRankingSounds.java"

events = json.loads(SOUNDS_JSON.read_text(encoding="utf-8"))
lines = [
    "package dev.killerranking;",
    "",
    "import net.minecraft.core.Registry;",
    "import net.minecraft.core.registries.BuiltInRegistries;",
    "import net.minecraft.server.level.ServerLevel;",
    "import net.minecraft.sounds.SoundEvent;",
    "import net.minecraft.sounds.SoundSource;",
    "import net.minecraft.world.entity.Entity;",
    "import net.minecraft.world.phys.Vec3;",
    "",
    "/** Generated by tools/sfx/gen_sounds_java.py from sounds.json. Do not edit by hand. */",
    "public final class KillerRankingSounds {",
]
names = []
for ev in events:
    const = ev.upper().replace(".", "_")
    names.append((const, ev))
    lines.append(f'    public static final SoundEvent {const} = SoundEvent.createVariableRangeEvent(KillerRankingMod.id("{ev}"));')
lines += [
    "",
    "    public static void register() {",
]
for const, ev in names:
    lines.append(f'        Registry.register(BuiltInRegistries.SOUND_EVENT, KillerRankingMod.id("{ev}"), {const});')
lines += [
    "    }",
    "",
    "    /** World-space one-shot heard by everyone nearby. */",
    "    public static void play(ServerLevel level, Vec3 at, SoundEvent sound, float volume, float pitch) {",
    "        level.playSound(null, at.x, at.y, at.z, sound, SoundSource.PLAYERS, volume, pitch);",
    "    }",
    "",
    "    public static void play(Entity at, SoundEvent sound, float volume, float pitch) {",
    "        if (at.level() instanceof ServerLevel level) play(level, at.position().add(0, at.getBbHeight() * 0.5, 0), sound, volume, pitch);",
    "    }",
    "",
    "    /** Slight random pitch so repeated strikes do not sound machine-gunned. */",
    "    public static float vary(Entity by, float pitch, float spread) {",
    "        return pitch + (by.getRandom().nextFloat() - 0.5f) * 2 * spread;",
    "    }",
    "",
    "    private KillerRankingSounds() { }",
    "}",
    "",
]
JAVA.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {JAVA.relative_to(ROOT)} with {len(names)} events")
